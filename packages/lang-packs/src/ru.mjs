export function segment(text) {
  return segmentLatin(text);
}

export function lemmatize(token) {
  if (!token) return token;
  let lower = foldYo(token.toLowerCase());
  const ex = applyExceptions(lower, EXCEPTIONS);
  if (ex) return ex;
  const v = stripSuffixes(lower, VERB_RULES);
  // 动名分流：动词规则命中后不再跑名词格尾（否则 читать→чита→чит；
  // 不定式 -ть 会被名词 -ь 规则吃掉）。名词走 else 分支，行为与旧版一致。
  if (v !== lower) return v;
  return stripSuffixes(lower, NOMINAL_RULES);
}

